-- ارسالی‌ها به مشتری وصل می‌شوند (۱۴۰۵/۰۶/۰۵)
--
-- تا امروز `shipments` فقط `customer_name`ِ متنی داشت. یعنی می‌شد ثبت کرد «۱۲ عدد
-- برای حاج قاسم به بندرعباس» ولی هیچ راهی نبود بپرسی «برای این مشتری تا حالا چه
-- فرستاده‌ام؟» — اسم متن بود، نه اشاره به کسی.
--
-- ستون **nullable** است و این عمدی است: ارسالی برای کسی که هنوز در لیستِ مشتری‌ها
-- نیست باید همچنان قابلِ ثبت باشد. پنل وقتی نام دقیقاً و **یکتا** با یک مشتری بخواند
-- خودش وصلش می‌کند و همان‌جا هم می‌گوید وصل شد یا نه، تا «وصل نشدن» بی‌صدا نماند.
--
-- ⚠️ `on delete set null` عمدی است، نه `no action` و نه `cascade`:
--   · با `no action` حذفِ مشتری با خطا می‌خوابید — همان دامی که `telegram_orders`
--     سرِ حذفِ فاکتور دارد و در README ثبت شده.
--   · با `cascade` سابقه‌ی ارسال با حذفِ مشتری پاک می‌شد، یعنی دادهٔ کسب‌وکار از
--     بین می‌رفت.
--   حالا ردیف می‌ماند، `customer_id` خالی می‌شود و `customer_name`ِ متنی‌اش سرِ جا
--   می‌مانَد — پس سابقه خوانا می‌مانَد حتی اگر مشتری حذف شود.
--
-- ایندکس لازم است چون صفحه‌ی مشتری روی همین ستون فیلتر می‌کند (DATA-07).
--
-- ⚠️ هیچ پرکردنِ گذشته‌ای لازم نیست و عمداً هم انجام نمی‌شود: قبل از این مهاجرت
-- جدول **خالی** بود (اندازه‌گیری شد: ۰ ردیف، ۷ مشتری). حدس‌زدنِ صاحبِ ارسالی از روی
-- تطبیقِ نام روی دادهٔ واقعی، ارسالی را به گردنِ آدمِ اشتباه می‌انداخت.

alter table public.shipments
  add column if not exists customer_id uuid
  references public.customers(id) on delete set null;

create index if not exists shipments_customer_id_idx
  on public.shipments(customer_id);

