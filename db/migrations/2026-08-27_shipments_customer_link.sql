-- ── چطور وارسی شد ───────────────────────────────────────────────────────────
-- ۱) کاتالوگ بعد از اجرا:
--      customer_id uuid nullable=YES
--      shipments_customer_id_fkey → SET NULL
--      shipments_customer_id_idx
--
-- ۲) **رفتار** هم سنجیده شد، نه فقط کاتالوگ — با همان الگوی تراکنشِ برگشت‌خورده:
--    مشتریِ آزمایشی + ارسالیِ وصل‌شده ساخته شد، مشتری حذف شد، و نتیجه:
--      ارسالی ماند: 1 ▸ customer_id بعدِ حذف: NULL ▸ نامِ متنی: __آزمونِ موقت__
--    یعنی هر سه چیزی که می‌خواستیم: ردیف پاک نشد، حذف با خطا نخوابید، و سابقه
--    با نامِ متنی‌اش خوانا ماند.
--
-- ۳) بعدش وارسی شد که چیزی جا نمانده باشد: مشتریِ جامانده ۰ · ارسالی ۰ · مشتری ۷.
